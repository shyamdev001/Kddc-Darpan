/**
 * Where media files live. `local` (dev: a folder on disk) and later `s3` (prod: Cloudflare R2).
 * Switch with STORAGE_DRIVER in .env; nothing else in the app should know which one is active.
 */
export interface StorageDriver {
  readonly name: 'local' | 's3';

  /** Moves a file from local disk into storage under `key`. The source file is consumed. */
  putFile(key: string, sourcePath: string, contentType: string): Promise<void>;

  /**
   * A local path the caller can read (e.g. to run FFmpeg on). Remote drivers download to a temp
   * file; always call `release()` when finished.
   */
  getLocalCopy(key: string): Promise<{ path: string; release: () => Promise<void> }>;

  /** Absolute path on this machine, or null when the driver is remote (serve via URL instead). */
  localPath(key: string): string | null;

  delete(key: string): Promise<void>;
}

export const STORAGE = Symbol('STORAGE');

/** Keys are generated by the app and ASCII-only: never a user's file name. */
const SAFE_KEY = /^[a-z0-9]+(?:[/_.-][a-z0-9]+)*$/;

export function assertSafeKey(key: string): void {
  if (!SAFE_KEY.test(key) || key.includes('..')) {
    throw new Error(`Unsafe storage key: ${key}`);
  }
}
